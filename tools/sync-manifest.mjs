// Single source for executable assets. Run after adding/removing adapter modules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const catalog = read('src/adapters/catalog.json').filter(m => m.enabled !== false);
if (new Set(catalog.map(m => m.id)).size !== catalog.length) throw Error('重复模块 id');
const main = ['src/runtime/catalog.js', 'src/runtime/page-runtime.js', ...catalog.flatMap(m => [m.page, ...(m.mainExtras || [])]), 'src/fallback/bridge.js'];
const isolated = ['src/core/text.js', 'src/core/util.js', 'src/core/regions-gb.js', 'src/core/region.js', 'src/core/convert.js', 'src/core/profile.js', 'src/core/mapping.js',
  'src/runtime/catalog.js', 'src/runtime/context.js', 'src/learning/memory.js', 'src/learning/scoped-memory.js', 'src/core/files.js', 'src/adapters/registry.js',
  ...catalog.flatMap(m => [m.mapping, ...(m.isolatedExtras || [])]), 'src/adapters/overrides.js', 'src/runtime/rpc.js', 'src/diagnostics/diagnostics.js',
  'src/fallback/scan.js', 'src/fallback/controls.js', 'src/fallback/dates.js', 'src/fallback/engine.js', 'src/fallback/field-fallback.js', 'src/workflow/attachments.js', 'src/workflow/engine.js', 'src/ui/panel.js'];
const manifest = read('manifest.json');
manifest.content_scripts[0].js = isolated;
manifest.content_scripts[1].js = main;
manifest.web_accessible_resources[0].resources = main;
const generated = '// Generated by tools/sync-manifest.mjs; edit adapters/catalog.json instead.\n' +
  `globalThis.AF_MODULES = ${JSON.stringify(catalog, null, 2)};\nglobalThis.AF_PAGE_SCRIPTS = ${JSON.stringify(main)};\n`;
const outputs = { 'manifest.json': JSON.stringify(manifest, null, 2) + '\n', 'src/runtime/catalog.js': generated };
if (process.argv.includes('--check')) {
  for (const [file, value] of Object.entries(outputs)) if (fs.readFileSync(path.join(root, file), 'utf8') !== value) throw Error(`请运行 node tools/sync-manifest.mjs：${file}`);
} else for (const [file, value] of Object.entries(outputs)) fs.writeFileSync(path.join(root, file), value);
for (const file of new Set([...isolated, ...main])) if (!fs.existsSync(path.join(root, file))) throw Error(`资源不存在：${file}`);
console.log('模块目录、manifest 与注入资源一致');
